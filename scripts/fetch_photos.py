#!/usr/bin/env python3
"""Bundle one photo per vibe into the app.

    python3 scripts/fetch_photos.py                # download from Pixabay (or Pexels) with a key
    python3 scripts/fetch_photos.py --force        # re-download every vibe, replacing existing photos
    python3 scripts/fetch_photos.py --index-only   # just rebuild the index from files already in app/assets/vibes/

Sources, in order of preference:
  PIXABAY_API_KEY  free key shown after signing up at https://pixabay.com/api/docs/
  PEXELS_API_KEY   free key at https://www.pexels.com/api/ (issuance is sometimes paused)
Put the key in the environment or in app/.env.local (git-ignored). Use names WITHOUT the EXPO_PUBLIC_
prefix so the key is never bundled into the app.

You can also drop your own photos into app/assets/vibes/ named <vibe-id>.jpg (for example pub.jpg,
dance.jpg; ids are in app/lib/vibes.ts) and run with --index-only. Unsplash downloads work well for this.
Photos already in app/assets/vibes/ (yours or downloaded) are kept unless you pass --force.

Photos are saved with photographer credits in credits.json. Never present a stock photo as a specific venue.
"""
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
OUT = APP / "assets" / "vibes"


def env_key(name):
    k = os.environ.get(name)
    f = APP / ".env.local"
    if not k and f.exists():
        m = re.search(rf"^{name}=(.+)$", f.read_text(), re.M)
        k = m.group(1).strip() if m else None
    return k


def vibes():
    src = (APP / "lib" / "vibes.ts").read_text()
    return re.findall(r"id: '([^']+)',.*?query: '([^']+)'", src)


def get(url, headers=None):
    req = urllib.request.Request(url, headers={"User-Agent": "DrunkVA-images/0.1", **(headers or {})})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def pixabay(key, query):
    qs = urllib.parse.urlencode({"key": key, "q": query, "image_type": "photo", "orientation": "vertical",
                                 "safesearch": "true", "order": "popular", "min_width": 800, "per_page": 5})
    hits = json.loads(get(f"https://pixabay.com/api/?{qs}")).get("hits", [])
    if not hits:
        return None
    h = hits[0]
    return get(h["largeImageURL"]), {"photographer": h["user"], "photographer_url": f"https://pixabay.com/users/{h['user']}-{h['user_id']}/", "photo_url": h["pageURL"], "source": "Pixabay"}


def pexels(key, query):
    qs = urllib.parse.urlencode({"query": query, "orientation": "portrait", "size": "medium", "per_page": 5})
    photos = json.loads(get(f"https://api.pexels.com/v1/search?{qs}", {"Authorization": key})).get("photos", [])
    if not photos:
        return None
    p = photos[0]
    return get(p["src"]["large"]), {"photographer": p["photographer"], "photographer_url": p["photographer_url"], "photo_url": p["url"], "source": "Pexels"}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    credits_file = OUT / "credits.json"
    credits = {c["vibe"]: c for c in json.loads(credits_file.read_text())} if credits_file.exists() else {}

    if "--index-only" not in sys.argv:
        source = next(((fn, k) for fn, k in ((pixabay, env_key("PIXABAY_API_KEY")), (pexels, env_key("PEXELS_API_KEY"))) if k), None)
        if not source:
            sys.exit("No key found. Set PIXABAY_API_KEY (or PEXELS_API_KEY) in the environment or app/.env.local, or use --index-only.")
        fn, key = source
        for vid, query in vibes():
            target = OUT / f"{vid}.jpg"
            if target.exists() and "--force" not in sys.argv:
                print(f"{vid}: already have a photo (use --force to replace)", file=sys.stderr)
                continue
            found = fn(key, query)
            if not found:
                print(f"{vid}: no photos for '{query}'", file=sys.stderr)
                continue
            target.write_bytes(found[0])
            credits[vid] = {"vibe": vid, **found[1]}
            print(f"{vid}: {found[1]['photographer']} ({found[1]['source']})", file=sys.stderr)

    have = sorted(p.stem for p in OUT.glob("*.jpg"))
    credits_file.write_text(json.dumps([credits[v] for v in have if v in credits], indent=1))
    body = ",\n".join(f"  '{v}': require('../assets/vibes/{v}.jpg')" for v in have)
    (APP / "lib" / "vibeImages.ts").write_text(
        "// GENERATED by scripts/fetch_photos.py. Do not edit by hand.\n"
        "// Maps a vibe id to a bundled photo. Screens fall back to a gradient and emoji for any vibe not listed.\n"
        "import type { ImageSource } from 'expo-image';\n\n"
        f"export const VIBE_IMAGES: Record<string, ImageSource | number> = {{\n{body}\n}};\n"
    )
    print(f"{len(have)} photos indexed", file=sys.stderr)


if __name__ == "__main__":
    main()
