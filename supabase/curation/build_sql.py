#!/usr/bin/env python3
"""Turn the filled-in curation CSVs into SQL.

    python3 supabase/curation/build_sql.py > supabase/migrations/005_curation_data.sql

Blank cells are skipped, so you can fill the files in gradually and re-run. Lists use `|`
(e.g. vibe: loud|dance floor). price_level is 1-4, age_19 is yes/no, verified_at is YYYY-MM-DD,
start_time is 24h HH:MM, stay_minutes is a whole number.
"""
import csv
import re
import sys
from pathlib import Path

here = Path(__file__).parent
errors = []


def q(s):
    return "'" + s.replace("'", "''") + "'"


def arr(s):
    return "array[" + ",".join(q(x.strip()) for x in s.split("|") if x.strip()) + "]::text[]"


def rows(name):
    with open(here / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def check(cond, msg):
    if not cond:
        errors.append(msg)
    return cond


out = ["-- Generated by supabase/curation/build_sql.py. Re-run safe. Do not edit by hand.\n"]

for r in rows("places.csv"):
    sets = []
    who = r["name"]
    for col in ("why_go", "tip", "music"):
        if r[col].strip():
            sets.append(f"{col} = {q(r[col].strip())}")
    for col in ("vibe", "best_for"):
        if r[col].strip():
            sets.append(f"{col} = {arr(r[col])}")
    if r["price_level"].strip():
        if check(r["price_level"].strip() in "1234" and len(r["price_level"].strip()) == 1, f"{who}: price_level must be 1-4"):
            sets.append(f"price_level = {r['price_level'].strip()}")
    if r["age_19"].strip():
        v = r["age_19"].strip().lower()
        if check(v in ("yes", "no"), f"{who}: age_19 must be yes or no"):
            sets.append(f"age_19 = {'true' if v == 'yes' else 'false'}")
    if r["verified_at"].strip():
        if check(re.fullmatch(r"\d{4}-\d\d-\d\d", r["verified_at"].strip()), f"{who}: verified_at must be YYYY-MM-DD"):
            sets.append(f"verified_at = {q(r['verified_at'].strip())}")
    if sets:
        out.append(f"update places set {', '.join(sets)} where source = 'osm' and source_id = {q(r['osm_id'])};")

for r in rows("experiences.csv"):
    sets = []
    for col in ("why_order", "best_night"):
        if r[col].strip():
            sets.append(f"{col} = {q(r[col].strip())}")
    if r["start_time"].strip():
        if check(re.fullmatch(r"([01]\d|2[0-3]):[0-5]\d", r["start_time"].strip()), f"{r['title']}: start_time must be HH:MM (24h)"):
            sets.append(f"start_time = {q(r['start_time'].strip())}")
    if sets:
        out.append(f"update experiences set {', '.join(sets)} where title = {q(r['title'])};")

for r in rows("stops.csv"):
    sets = []
    who = f"{r['experience']} #{r['position']}"
    if r["stay_minutes"].strip():
        if check(r["stay_minutes"].strip().isdigit() and int(r["stay_minutes"]) > 0, f"{who}: stay_minutes must be a positive whole number"):
            sets.append(f"stay_minutes = {int(r['stay_minutes'])}")
    if r["tip"].strip():
        sets.append(f"tip = {q(r['tip'].strip())}")
    if sets:
        out.append(
            f"update experience_stops set {', '.join(sets)} where position = {int(r['position'])} "
            f"and experience_id = (select id from experiences where title = {q(r['experience'])});"
        )

if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)
print("\n".join(out))
